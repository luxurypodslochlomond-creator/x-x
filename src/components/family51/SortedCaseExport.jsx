import { useState } from 'react';
import { motion } from 'framer-motion';

const TOOL_CONFIG = {
  letter:   { label: 'DECODED', color: '#d97706' },
  reply:    { label: 'REPLY',   color: '#0891b2' },
  conflict: { label: 'DISPUTE', color: '#ef4444' },
};

function parseResult(ai_result) {
  if (!ai_result) return null;
  try { return JSON.parse(ai_result); } catch { return null; }
}
function safeStr(val) {
  if (!val) return val;
  if (typeof val === 'string') return val;
  if (typeof val === 'object') return JSON.stringify(val);
  return String(val);
}
function hexToRgb(hex) {
  const h = (hex || '#000').replace('#', '');
  const n = parseInt(h.length === 3 ? h.split('').map(c => c + c).join('') : h, 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

export function slugify(s) {
  return (s || '').toString().toLowerCase()
    .replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 50) || 'case';
}

export function buildCaseFileName(caseItem) {
  const d = new Date(caseItem.created_date || Date.now());
  const dateStr = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
  return `SortedSOS — ${slugify(caseItem.summary || caseItem.tool)} — ${dateStr}.pdf`;
}

// Shared section builder so text, PDF and email all stay in sync
export function buildCaseSections(caseItem) {
  const parsed = parseResult(caseItem.ai_result);
  const tool = TOOL_CONFIG[caseItem.tool] || TOOL_CONFIG.letter;
  const sections = [];
  if (!parsed) return sections;
  if (caseItem.tool === 'letter') {
    if (parsed.we_hear_you) sections.push({ label: 'WE HEAR YOU', body: safeStr(parsed.we_hear_you) });
    if (parsed.what_this_means) sections.push({ label: 'WHAT IT MEANS', body: safeStr(parsed.what_this_means), accent: tool.color });
    if (parsed.if_you_ignore_this) sections.push({ label: 'IF YOU IGNORE THIS', body: safeStr(parsed.if_you_ignore_this), accent: '#ef4444' });
    if (parsed.action_steps?.length) sections.push({ label: 'WHAT TO DO', body: parsed.action_steps.map((s, i) => `${i + 1}. ${safeStr(s)}`).join('\n'), accent: '#22c55e' });
    if (parsed.key_deadline && parsed.key_deadline !== 'No deadline mentioned') sections.push({ label: 'DEADLINE', body: safeStr(parsed.key_deadline), accent: '#d97706' });
  } else if (caseItem.tool === 'reply') {
    if (parsed.subject_line) sections.push({ label: 'SUBJECT LINE', body: safeStr(parsed.subject_line), accent: tool.color });
    if (parsed.letter_body) sections.push({ label: 'YOUR REPLY LETTER', body: safeStr(parsed.letter_body), accent: tool.color });
    if (parsed.tip) sections.push({ label: 'TOP TIP', body: safeStr(parsed.tip), accent: '#eab308' });
  } else if (caseItem.tool === 'conflict') {
    if (parsed.situation_assessment) sections.push({ label: 'ASSESSMENT', body: safeStr(parsed.situation_assessment), accent: tool.color });
    if (parsed.legal_position) sections.push({ label: 'YOUR LEGAL POSITION', body: safeStr(parsed.legal_position), accent: '#06b6d4' });
    if (parsed.what_to_say) sections.push({ label: 'WHAT TO SAY', body: safeStr(parsed.what_to_say), accent: '#22c55e' });
    if (parsed.recommended_steps?.length) sections.push({ label: 'NEXT STEPS', body: parsed.recommended_steps.map((s, i) => `${i + 1}. ${safeStr(s)}`).join('\n'), accent: '#22c55e' });
  }
  return sections;
}

export function buildCaseText(caseItem) {
  const tool = TOOL_CONFIG[caseItem.tool] || TOOL_CONFIG.letter;
  const sections = buildCaseSections(caseItem);
  const d = new Date(caseItem.created_date || Date.now());
  let text = `SortedSOS — Case File\n${'='.repeat(40)}\n`;
  text += `Type: ${tool.label}\n`;
  text += `Date: ${d.toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' })}\n`;
  text += `Severity: ${(caseItem.severity || 'unknown').toUpperCase()}\n`;
  text += `Summary: ${caseItem.summary || ''}\n\n`;
  for (const s of sections) text += `${s.label}\n${safeStr(s.body)}\n\n`;
  if (caseItem.input_text) text += `WHAT YOU SENT\n${caseItem.input_text.slice(0, 1000)}${caseItem.input_text.length > 1000 ? '…' : ''}\n\n`;
  text += `${'─'.repeat(40)}\nGenerated by SortedSOS — sortedsos.org`;
  return text;
}

export async function buildCasePDFBlob(caseItem) {
  const { jsPDF } = await import('jspdf');
  const tool = TOOL_CONFIG[caseItem.tool] || TOOL_CONFIG.letter;
  const sections = buildCaseSections(caseItem);
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const pageW = doc.internal.pageSize.getWidth();
  const pageH = doc.internal.pageSize.getHeight();
  const M = 48;
  const CW = pageW - M * 2;
  let y = M;

  // Title
  doc.setFont('helvetica', 'bold'); doc.setFontSize(22); doc.setTextColor(26, 18, 8);
  doc.text('SortedSOS', M, y);
  y += 20;
  doc.setFont('helvetica', 'normal'); doc.setFontSize(10); doc.setTextColor(150, 140, 130);
  doc.text('Case File', M, y);
  y += 8;
  const [tr, tg, tb] = hexToRgb(tool.color);
  doc.setDrawColor(tr, tg, tb); doc.setLineWidth(2.5);
  doc.line(M, y, M + 44, y);
  y += 18;

  // Meta
  doc.setFontSize(9); doc.setTextColor(120, 110, 100);
  const d = new Date(caseItem.created_date || Date.now());
  const meta = `Type: ${tool.label}   ·   Date: ${d.toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' })}   ·   Severity: ${(caseItem.severity || 'unknown').toUpperCase()}`;
  doc.text(doc.splitTextToSize(meta, CW), M, y);
  y += 16;

  // Summary
  if (caseItem.summary) {
    doc.setFont('helvetica', 'bold'); doc.setFontSize(14); doc.setTextColor(26, 18, 8);
    const sumLines = doc.splitTextToSize(caseItem.summary, CW);
    doc.text(sumLines, M, y);
    y += sumLines.length * 17 + 10;
  }

  const addWrapped = (text, size, color) => {
    doc.setFont('helvetica', 'normal'); doc.setFontSize(size);
    const [rr, gg, bb] = hexToRgb(color || '#2a2018');
    doc.setTextColor(rr, gg, bb);
    const lines = doc.splitTextToSize(String(text), CW);
    for (const line of lines) {
      if (y > pageH - M) { doc.addPage(); y = M; }
      doc.text(line, M, y);
      y += size + 4;
    }
  };

  for (const s of sections) {
    if (y > pageH - M - 60) { doc.addPage(); y = M; }
    doc.setFont('helvetica', 'bold'); doc.setFontSize(9);
    const [rr, gg, bb] = hexToRgb(s.accent || '#6b6258');
    doc.setTextColor(rr, gg, bb);
    doc.text(s.label, M, y);
    y += 14;
    addWrapped(s.body, 11, '#2a2018');
    y += 12;
  }

  // What you sent (appendix)
  if (caseItem.input_text) {
    if (y > pageH - M - 80) { doc.addPage(); y = M; }
    doc.setFont('helvetica', 'bold'); doc.setFontSize(9); doc.setTextColor(120, 110, 100);
    doc.text('WHAT YOU SENT', M, y); y += 14;
    addWrapped(caseItem.input_text.slice(0, 1500) + (caseItem.input_text.length > 1500 ? '…' : ''), 10, '#6b6258');
    y += 12;
  }

  // Footer
  if (y > pageH - M - 30) { doc.addPage(); y = M; }
  const fy = pageH - M - 6;
  doc.setDrawColor(225, 220, 213); doc.setLineWidth(0.5); doc.line(M, fy, pageW - M, fy);
  doc.setFont('helvetica', 'normal'); doc.setFontSize(8); doc.setTextColor(150, 140, 130);
  doc.text('Generated by SortedSOS  ·  sortedsos.org  ·  Private to you', M, fy + 12);

  return doc.output('blob');
}

export function buildShareText(caseItem) {
  const parsed = parseResult(caseItem.ai_result);
  const anon = (s) => (s || '')
    .replace(/\b[A-Z][a-z]+ [A-Z][a-z]+\b/g, '[Name]')
    .replace(/£\d[\d,.]*/g, '[amount]')
    .replace(/\$\d[\d,.]*/g, '[amount]')
    .replace(/\d{1,2}\/\d{1,2}\/\d{2,4}/g, '[date]');
  let text = 'SortedSOS decoded a letter for me:\n\n';
  if (parsed?.what_this_means) text += anon(safeStr(parsed.what_this_means)) + '\n\n';
  if (parsed?.action_steps?.length) text += 'Steps:\n' + parsed.action_steps.map((s, i) => `${i + 1}. ${anon(safeStr(s))}`).join('\n') + '\n\n';
  text += 'Free legal letter decoder → sortedsos.org';
  return text.trim();
}

export function buildEmail(caseItem) {
  const sections = buildCaseSections(caseItem);
  let body = '';
  for (const s of sections) body += `${s.label}\n${safeStr(s.body)}\n\n`;
  if (caseItem.input_text) body += `WHAT YOU SENT\n${caseItem.input_text.slice(0, 1000)}${caseItem.input_text.length > 1000 ? '…' : ''}\n\n`;
  body += '—\nSent via SortedSOS  ·  sortedsos.org';
  return { subject: `SortedSOS — ${caseItem.summary || 'Case File'}`, body: body.trim() };
}

// ── Native-feel segmented action bar ──
export function CaseActionBar({ actions }) {
  const [pressed, setPressed] = useState(null);
  return (
    <div style={{
      display: 'flex', borderRadius: 14, overflow: 'hidden',
      border: '1px solid rgba(26,18,8,0.09)',
      background: 'rgba(26,18,8,0.015)',
    }}>
      {actions.map((a, i) => {
        const Icon = a.icon;
        const isPressed = pressed === i;
        return (
          <motion.button
            key={i}
            whileTap={{ scale: 0.97 }}
            onPointerDown={() => setPressed(i)}
            onPointerUp={() => setPressed(null)}
            onPointerLeave={() => setPressed(null)}
            onClick={(e) => { e.stopPropagation(); a.onClick(); }}
            style={{
              flex: 1, display: 'flex', flexDirection: 'column', alignItems: 'center', gap: 5,
              padding: '13px 6px', cursor: 'pointer', border: 'none',
              borderLeft: i > 0 ? '1px solid rgba(26,18,8,0.07)' : 'none',
              background: isPressed ? (a.accent ? `${a.accent}14` : 'rgba(26,18,8,0.05)') : 'transparent',
              transition: 'background 0.12s',
            }}
          >
            <Icon size={17} color={a.accent || 'rgba(26,18,8,0.55)'} strokeWidth={2.2} />
            <span style={{ fontSize: 9.5, fontWeight: 900, letterSpacing: '0.1em', color: a.accent || 'rgba(26,18,8,0.5)' }}>{a.label}</span>
          </motion.button>
        );
      })}
    </div>
  );
}