// ── MAIN EXPORT ──
export default function SortedCaseHistory({ onContinue, isPremium = false }) {
  const [cases, setCases] = useState([]);
  const [filter, setFilter] = useState('all');
  const [confirmWipe, setConfirmWipe] = useState(false);

  const loadCases = () => {
    try {
      const stored = JSON.parse(localStorage.getItem(STORAGE_KEY) || '[]');
      setCases(stored);
    } catch { setCases([]); }
  };

  useEffect(() => {
    loadCases();
    window.addEventListener('visibilitychange', loadCases);
    return () => window.removeEventListener('visibilitychange', loadCases);
  }, []);

  const handleDelete = (id) => {
    const updated = cases.filter(c => c.id !== id);
    setCases(updated);
    try { localStorage.setItem(STORAGE_KEY, JSON.stringify(updated)); window.dispatchEvent(new CustomEvent('sorted-cases-changed')); } catch {}
  };

  const handleEdit = (id, newSummary) => {
    const updated = cases.map(c => c.id === id ? { ...c, summary: newSummary } : c);
    setCases(updated);
    try { localStorage.setItem(STORAGE_KEY, JSON.stringify(updated)); window.dispatchEvent(new CustomEvent('sorted-cases-changed')); } catch {}
  };

  const handleWipeAll = () => {
    if (!confirmWipe) { setConfirmWipe(true); return; }
    setCases([]);
    try { localStorage.setItem(STORAGE_KEY, JSON.stringify([])); window.dispatchEvent(new CustomEvent('sorted-cases-changed')); } catch {}
    setConfirmWipe(false);
  };

  const filtered = filter === 'all' ? cases : cases.filter(c => c.tool === filter);

  if (!isPremium && cases.length === 0) return null;

  const filterTabs = [
    { id: 'all',      label: 'ALL',      color: '#1a1208' },
    { id: 'letter',   label: 'DECODED',  color: '#d97706' },
    { id: 'reply',    label: 'REPLIES',  color: '#0891b2' },
    { id: 'conflict', label: 'DISPUTES', color: '#ef4444' },
  ];

  return (
    <div style={{ maxWidth: 560, margin: '0 auto', padding: '32px 20px 60px' }}>
      <VaultHeader count={cases.length} isPremium={isPremium} />

      {/* FILTER TABS */}
      {cases.length > 0 && (
        <div style={{ display: 'flex', gap: 8, marginBottom: 20, overflowX: 'auto', paddingBottom: 2 }}>
          {filterTabs.map(tab => {
            const count = tab.id === 'all' ? cases.length : cases.filter(c => c.tool === tab.id).length;
            const active = filter === tab.id;
            return (
              <button
                key={tab.id}
                onClick={() => setFilter(tab.id)}
                style={{
                  padding: '8px 16px', borderRadius: 24, fontSize: 11, fontWeight: 800,
                  letterSpacing: '0.08em', cursor: 'pointer', whiteSpace: 'nowrap',
                  border: `1.5px solid ${active ? tab.color + '60' : 'rgba(26,18,8,0.08)'}`,
                  background: active ? `${tab.color}12` : 'rgba(26,18,8,0.02)',
                  color: active ? tab.color : 'rgba(26,18,8,0.4)',
                  transition: 'all 0.15s',
                  display: 'flex', alignItems: 'center', gap: 6,
                }}
              >
                {tab.label}
                {count > 0 && (
                  <span style={{
                    fontSize: 10, fontWeight: 900,
                    background: active ? `${tab.color}20` : 'rgba(26,18,8,0.06)',
                    borderRadius: 10, padding: '1px 6px',
                    color: active ? tab.color : 'rgba(26,18,8,0.3)',
                  }}>{count}</span>
                )}
              </button>
            );
          })}
        </div>
      )}

      {/* CASES */}
      {filtered.length === 0 ? (
        <div style={{
          textAlign: 'center', padding: '52px 24px',
          border: '1.5px dashed rgba(217,119,6,0.15)', borderRadius: 16,
          background: 'rgba(217,119,6,0.02)',
        }}>
          <div style={{
            width: 56, height: 56, borderRadius: 14, margin: '0 auto 16px',
            background: 'rgba(217,119,6,0.06)', border: '1.5px solid rgba(217,119,6,0.15)',
            display: 'flex', alignItems: 'center', justifyContent: 'center',
          }}>
            <Archive size={26} color="rgba(217,119,6,0.35)" strokeWidth={1.8} />
          </div>
          <p style={{ fontSize: 15, fontWeight: 700, color: 'rgba(26,18,8,0.5)', margin: '0 0 6px' }}>
            {cases.length === 0 ? 'Your vault is empty' : 'No cases of this type'}
          </p>
          <p style={{ fontSize: 13, color: 'rgba(26,18,8,0.35)', margin: 0, lineHeight: 1.6 }}>
            {cases.length === 0 ? 'Decode a letter and it lands here — safe, private, ready when you need it.' : 'Try a different filter.'}
          </p>
        </div>
      ) : (
        <div style={{ display: 'flex', flexDirection: 'column', gap: 12 }}>
          <AnimatePresence mode="popLayout">
            {filtered.map(c => (
              <CaseCard
                key={c.id}
                caseItem={c}
                onDelete={handleDelete}
                onContinue={onContinue}
                onEdit={handleEdit}
                onFollowUpSaved={loadCases}
                linkedReplies={c.tool === 'letter' ? cases.filter(x => x.tool === 'reply' && x.related_case_id === c.id) : []}
                linkedConflicts={c.tool !== 'conflict' ? cases.filter(x => x.tool === 'conflict' && x.related_case_id === c.id) : []}
              />
            ))}
          </AnimatePresence>
        </div>
      )}

      {/* WIPE ALL — premium only, bottom */}
      {isPremium && cases.length > 0 && (
        <div style={{ marginTop: 24, textAlign: 'center' }}>
          <motion.button
            onClick={handleWipeAll}
            whileTap={{ scale: 0.95 }}
            style={{
              padding: '10px 20px', borderRadius: 10, fontSize: 11, fontWeight: 700,
              cursor: 'pointer', border: 'none', background: 'transparent',
              color: confirmWipe ? '#ef4444' : 'rgba(26,18,8,0.25)',
              display: 'inline-flex', alignItems: 'center', gap: 6,
            }}
          >
            <Trash2 size={13} />
            {confirmWipe ? 'TAP AGAIN TO WIPE VAULT' : 'Wipe entire vault'}
          </motion.button>
        </div>
      )}
    </div>
  );
}