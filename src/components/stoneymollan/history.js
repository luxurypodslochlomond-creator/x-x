// ── THE HISTORY OF THE HILL ──
// Rewritten after the founder pulled me up on two things, both of which were right.
//
// ONE: the geography. Cardross is not across the water from this hill. The old parish of
// Cardross ran across this hill to St Serf's by the Leven, and Bruce's manor lay there —
// five or six miles south, over the hills, no water to cross. "Across the water" was wrong
// and it is gone.
//
// TWO: directness. A page about Stoneymollan should not drift into general Loch Lomond
// colour. So each person below now carries the distance from this hill, because distance
// is checkable, and where no record puts them on this road, the entry says so out loud.
//
// Where a thing rests on one popular history rather than on a record — Rob Roy's raid on
// Inchmurrin, the exact site of Bruce's manor — it is attributed or hedged rather than
// stated. A hill this small does not need to invent anything.

