// Brian, 26 November: "what [difference] between action and solution — look [the] same
// to me in places." He was right, and the reason was simple: the record had never
// written its own three words down anywhere a reader meets them. The definitions band
// quotes Geodesign, Rewilding and Blue Carbon from the bodies that defined them, and
// said nothing at all about the three words stamped on every single entry.
//
// These are not quoted, because there is nobody to quote: they are the record's own
// working words, and the band says so above them, so a reader never mistakes them for
// a definition borrowed from a body with authority.
//
// The test that separates the last two is the only one that has ever held: a solution
// has no date on it, an action does. "Seagrass planting works" is a solution. "The
// school planted four hundred metres on the 12th" is an action. A crisis is the thing
// both of them are answering.
